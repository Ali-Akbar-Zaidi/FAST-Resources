    private void btnConvertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConvertActionPerformed
        try{
            float from = Float.parseFloat(txtTemp.getText());
            float to = convert(from);
            
            lblTo.setText(to + (option == 1 ? " Fahrenheit" : " Celcius"));
            
        } catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(getContentPane(), "Invalid number");
            txtTemp.setText("");
        }       
    }//GEN-LAST:event_btnConvertActionPerformed

