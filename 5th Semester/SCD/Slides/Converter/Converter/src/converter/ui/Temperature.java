    private float convert(float v){
        float r = 0;
        if (option == 1){
            r = v * 9 / 5 + 32;
        }
        else {
            r = (v - 32) * 5 / 9; 
        }
        r = (float) Math.round(r * 10) / 10;
        
        return r;
    }
    
